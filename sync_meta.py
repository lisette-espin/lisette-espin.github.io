#!/usr/bin/env python3
"""Copy the `meta` block of data/dashboard.js into the head of index.html.

build.py runs this for you; you rarely need to call it yourself.

Link-preview scrapers — LinkedIn, Slack, X, Bluesky, WhatsApp — fetch the HTML
and read it without running any JavaScript, so they never see the tags app.js
writes. index.html therefore keeps a static copy of the handful of tags that
matter to them. This script regenerates that copy, so the two cannot drift.

Run it after editing `meta` in data/dashboard.js:

    python3 sync_meta.py

It rewrites only what sits between the STATIC META markers and reports whether
anything changed. Everything else about the page still comes from the data file
at load; this is only a fallback for readers that do not run scripts.
"""

import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
INDEX = HERE / "index.html"
DATA = HERE / "data" / "dashboard.js"

START = "<!-- STATIC META START"
END = "<!-- STATIC META END -->"

HEADER = """<!-- STATIC META START — generated by sync_meta.py from data/dashboard.js.
     Link-preview scrapers (LinkedIn, Slack, X, Bluesky) read this file without
     running scripts, so these tags are what they see. app.js rewrites them from
     the data file once the page loads, so the two always agree in a browser.
     Do not hand-edit: change meta in data/content.json and run `python3 build.py`. -->"""


def absolute(path, site_url):
    """A site-relative path turned into a full URL, which previews require."""
    if not path or not site_url or re.match(r"^(https?:|data:)", path):
        return path
    return site_url.rstrip("/") + "/" + path.lstrip("/")


def esc(value):
    return html.escape(str(value), quote=True)


def build(record):
    meta = record.get("meta", {})
    profile = record.get("profile", {})
    name = meta.get("author") or profile.get("name", "")
    title = meta.get("title") or name
    site = meta.get("siteUrl")
    short = meta.get("shortDescription") or meta.get("description")
    image = absolute(meta.get("ogImage") or profile.get("headshot"), site)

    lines = [HEADER, f"<title>{esc(title)}</title>"]
    for attr, key, value in (
        ("name", "description", meta.get("description")),
        ("property", "og:type", "profile"),
        ("property", "og:title", title),
        ("property", "og:description", short),
        ("property", "og:image", image),
        ("property", "og:url", site),
        ("name", "twitter:card", "summary"),
    ):
        if value:
            lines.append(f'<meta {attr}="{key}" content="{esc(value)}">')
    lines.append(END)
    return "\n".join(lines)


def main():
    raw = DATA.read_text(encoding="utf-8")
    record = json.loads(raw[raw.index("=") + 1:].rstrip().rstrip(";"))

    page = INDEX.read_text(encoding="utf-8")
    if START not in page or END not in page:
        sys.exit(
            f"{INDEX.name} has no STATIC META markers. Add these two lines to the\n"
            f"head, and this script will fill in between them:\n"
            f"    {START} -->\n    {END}")

    before = page[:page.index(START)]
    after = page[page.index(END) + len(END):]
    updated = before + build(record) + after

    if updated == page:
        print("index.html already matches data/dashboard.js — nothing to do.")
        return
    INDEX.write_text(updated, encoding="utf-8")
    print("index.html head updated from data/dashboard.js.")


if __name__ == "__main__":
    main()
